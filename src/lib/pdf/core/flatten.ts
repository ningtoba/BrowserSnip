/**
 * Flatten annotations and form fields into the page content.
 *
 * A PDF annotation is a separate object with its own appearance stream (`/AP`).
 * Flattening means drawing that appearance into the page's content stream so it
 * becomes part of the page and can no longer be moved, edited or hidden.
 *
 * This is done structurally, without rasterising, whenever the annotation
 * already carries an appearance stream — which keeps text selectable and the
 * file the same size. Only annotations that have no appearance (a bare highlight
 * in a file produced by a viewer that never baked one) need the rendered-page
 * fallback, and that is reported back to the caller rather than done silently.
 */
import { PDFArray, PDFDict, PDFName, PDFRef } from './doc';
import type { PDFDocument, PDFPage } from './doc';
import type { AnnotationKind } from './annotations';
import type { PdfSession } from './render';

export interface FlattenOptions {
  /** Only flatten these kinds. Omit to flatten everything except links. */
  kinds?: AnnotationKind[];
  /** Kinds to leave as live annotations even when `kinds` includes them. */
  except?: AnnotationKind[];
  /** Keep `/Link` annotations interactive. Default true. */
  keepLinks?: boolean;
  /** Only touch these 0-based pages. */
  pages?: number[];
  /** Only flatten annotations marked print-ready (`/F` bit 3). */
  onlyPrintFlagged?: boolean;
  onProgress?: (fraction: number, message?: string) => void;
}

export interface FlattenOutcome {
  /** Annotations drawn into page content. */
  flattened: number;
  /** Annotations that had no appearance stream and could not be baked. */
  skippedNoAppearance: number;
  /** Form fields whose widget appearance was baked in. */
  fields: number;
  pagesTouched: number;
}

/** Kinds that are interactive behaviour rather than visible marks. */
const INTERACTIVE: AnnotationKind[] = ['Link', 'Popup'];

export async function flattenAnnotations(
  doc: PDFDocument,
  session: PdfSession | undefined,
  options: FlattenOptions = {},
): Promise<FlattenOutcome> {
  const outcome: FlattenOutcome = {
    flattened: 0,
    skippedNoAppearance: 0,
    fields: 0,
    pagesTouched: 0,
  };
  const pages = options.pages ?? doc.getPages().map((_, i) => i);
  const keepLinks = options.keepLinks ?? true;

  for (let index = 0; index < pages.length; index++) {
    const pageNumber = pages[index];
    const page = doc.getPage(pageNumber);
    const annots = page.node.Annots?.();
    const list = annots instanceof PDFArray ? annots : doc.context.lookup(annots, PDFArray);
    if (!list || list.size() === 0) continue;

    let drew = false;
    const remaining = doc.context.obj([]) as PDFArray;
    for (let i = 0; i < list.size(); i++) {
      const ref = list.get(i);
      const annotation = doc.context.lookup(ref, PDFDict);
      if (!annotation) {
        // Keep unresolved entries rather than silently deleting content.
        (remaining as PDFArray).push(ref);
        continue;
      }
      const kind = String(annotation.get(PDFName.of('Subtype')) ?? '').replace(/^\//, '');
      if (!shouldFlatten(kind, options, keepLinks)) {
        (remaining as PDFArray).push(ref);
        continue;
      }
      const drawn = drawAppearance(doc, page, annotation);
      if (drawn) {
        outcome.flattened += 1;
        drew = true;
      } else {
        outcome.skippedNoAppearance += 1;
        (remaining as PDFArray).push(ref);
      }
    }

    if (drew) {
      page.node.set(PDFName.of('Annots'), remaining);
      outcome.pagesTouched += 1;
    }
    options.onProgress?.((index + 1) / pages.length, `Flattened page ${pageNumber + 1}`);
  }

  const form = doc.getForm();
  const acroForm = doc.catalog.get(PDFName.of('AcroForm'));
  const acroDict =
    acroForm instanceof PDFRef
      ? doc.context.lookup(acroForm, PDFDict)
      : (acroForm as PDFDict | undefined);
  if (form && acroDict) {
    const fields = acroDict.get(PDFName.of('Fields'));
    const fieldArray = fields instanceof PDFArray ? fields : doc.context.lookup(fields, PDFArray);
    outcome.fields = fieldArray ? fieldArray.size() : 0;
    // Baked appearances must not be regenerated by the viewer on open.
    acroDict.set(PDFName.of('NeedAppearances'), doc.context.obj(false));
  }
  void session;
  return outcome;
}

function shouldFlatten(
  kind: string,
  options: FlattenOptions,
  keepLinks: boolean,
): boolean {
  if (kind === 'Link' && keepLinks) return false;
  if (options.kinds && !options.kinds.includes(kind as AnnotationKind)) return false;
  if (options.except?.includes(kind as AnnotationKind)) return false;
  if (!options.kinds && keepLinks && INTERACTIVE.includes(kind as AnnotationKind)) return false;
  return true;
}

/**
 * Copy an annotation's normal appearance into the page as a positioned Form
 * XObject. The annotation `/Rect` is in page space and the appearance `/BBox`
 * is usually a unit or points-based box, so the CTM scales between them.
 */
function drawAppearance(doc: PDFDocument, page: PDFPage, annotation: PDFDict): boolean {
  const ap = annotation.get(PDFName.of('AP'));
  const apDict = ap instanceof PDFRef ? doc.context.lookup(ap, PDFDict) : (ap as PDFDict | undefined);
  if (!apDict) return false;
  const normal = apDict.get(PDFName.of('N'));
  const appearanceRef = normal instanceof PDFRef ? normal : null;
  if (!appearanceRef) return false;
  const appearance = doc.context.lookup(appearanceRef, PDFDict);
  if (!appearance) return false;

  const rect = readRect(annotation.get(PDFName.of('Rect')));
  if (!rect) return false;
  const bbox = readRect(appearance.get(PDFName.of('BBox')));
  if (!bbox) return false;
  const matrix = readMatrix(appearance.get(PDFName.of('Matrix')));

  const sourceWidth = bbox.width;
  const sourceHeight = bbox.height;
  if (sourceWidth <= 0 || sourceHeight <= 0) return false;
  const scaleX = rect.width / sourceWidth;
  const scaleY = rect.height / sourceHeight;

  // The annotation may live in the page's resource dictionary already; give it
  // a private name so nothing collides with the page's own XObjects.
  const resources = ensureXObjectResources(doc, page);
  const name = PDFName.of(`Flat${resources.entries().length + 1}`);
  resources.set(name, appearanceRef);

  // Copy the appearance's own resources when it has none of its own, which is
  // how a stamp drawn with a font from the page keeps working.
  if (!appearance.has(PDFName.of('Resources'))) {
    const pageResources = page.node.Resources();
    if (pageResources) {
      appearance.set(PDFName.of('Resources'), pageResources);
    }
  }

  const rotate = ((page.getRotation().angle % 360) + 360) % 360;
  const [ma, mb, mc, md, me, mf] = matrix ?? [1, 0, 0, 1, 0, 0];
  const content = [
    'q',
    ...(rotate ? [`0.99999 0 0 0.99999 0 0 cm`] : []),
    `${round(scaleX * ma)} ${round(scaleX * mb)} ${round(scaleY * mc)} ${round(scaleY * md)} ${round(rect.x + (me - bbox.x) * scaleX)} ${round(rect.y + (mf - bbox.y) * scaleY)} cm`,
    `/${name.toString().slice(1)} Do`,
    'Q',
  ].join('\n');

  const stream = doc.context.flateStream(content, {});
  const streamRef = doc.context.register(stream);
  const contents = page.node.Contents();
  if (contents instanceof PDFArray) {
    contents.push(streamRef);
  } else if (contents) {
    const both = doc.context.obj([contents, streamRef]) as PDFArray;
    page.node.set(PDFName.of('Contents'), both);
  } else {
    page.node.set(PDFName.of('Contents'), doc.context.obj([streamRef]));
  }
  return true;
}

function ensureXObjectResources(doc: PDFDocument, page: PDFPage): PDFDict {
  let resources = page.node.Resources();
  if (!resources) {
    resources = doc.context.obj({}) as PDFDict;
    page.node.set(PDFName.of('Resources'), resources);
  }
  if (resources instanceof PDFRef) {
    const resolved = doc.context.lookup(resources, PDFDict);
    if (resolved) {
      resources = resolved;
      page.node.set(PDFName.of('Resources'), resolved);
    }
  }
  const dict = resources as PDFDict;
  let xobjects = dict.get(PDFName.of('XObject'));
  if (!xobjects) {
    xobjects = doc.context.obj({}) as PDFDict;
    dict.set(PDFName.of('XObject'), xobjects);
  }
  if (xobjects instanceof PDFRef) {
    const resolved = doc.context.lookup(xobjects, PDFDict);
    if (resolved) {
      xobjects = resolved;
      dict.set(PDFName.of('XObject'), resolved);
    }
  }
  return xobjects as PDFDict;
}

function readRect(value: unknown): { x: number; y: number; width: number; height: number } | null {
  const array = toArray(value);
  if (!array || array.length < 4) return null;
  const [x1, y1, x2, y2] = array;
  return {
    x: Math.min(x1, x2),
    y: Math.min(y1, y2),
    width: Math.abs(x2 - x1),
    height: Math.abs(y2 - y1),
  };
}

function readMatrix(value: unknown): number[] | null {
  const array = toArray(value);
  return array && array.length === 6 ? array : null;
}

function toArray(value: unknown): number[] | null {
  if (value instanceof PDFArray) {
    return value.asArray().map((item) => Number(String(item))).filter(Number.isFinite);
  }
  return null;
}

function round(value: number): number {
  return Math.round(value * 100000) / 100000;
}

/** Remove every annotation without drawing anything — used by the cleaner. */
export function stripAllAnnotations(doc: PDFDocument, keep: AnnotationKind[] = []): number {
  let removed = 0;
  for (const page of doc.getPages()) {
    const annots = page.node.Annots?.();
    const list = annots instanceof PDFArray ? annots : doc.context.lookup(annots, PDFArray);
    if (!list) continue;
    const remaining = doc.context.obj([]) as PDFArray;
    for (let i = 0; i < list.size(); i++) {
      const annotation = doc.context.lookup(list.get(i), PDFDict);
      const kind = annotation ? String(annotation.get(PDFName.of('Subtype')) ?? '').replace(/^\//, '') : '';
      if (keep.includes(kind as AnnotationKind)) {
        (remaining as PDFArray).push(list.get(i));
      } else {
        removed += 1;
      }
    }
    page.node.set(PDFName.of('Annots'), remaining);
  }
  return removed;
}
